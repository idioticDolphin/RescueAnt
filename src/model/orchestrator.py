logger = logging.getLogger(__name__)

discovery_queries: list[str] = []  # search queries generated by init(), consumed by run_discovery()
# (pages worth extracting, pages fetched) for the last rounds - what the
# frontier actually produced, as against what its scores promised.
recent_yield: list[tuple[int, int]] = []
YIELD_HISTORY = 50
_round_tally = [0, 0]  # this round so far: worth extracting, classified


def init():
    """
    Prepare a crawl run: initialize the database schema, seed the fetch
    queue from starting_urls/prior crawls (model.crawler.fetching_service.init()),
    and - if search-based discovery is enabled in the config - generate and
    store the search queries later consumed by run_discovery().
    """
    config = config_service.get_config()
    data_service.init_db()
    page_store.configure(config.page_store_path)
    fetching_service.init(
        starting_url_path = config.get_starting_url_path(),
        redo_failed_fetches=config.redo_failed_fetches,
        redo_all_fetches=config.redo_all_fetches
    )
    recall_frontier(config)
    global discovery_queries
    discovery_queries = discovery_service.read_query_templates(config.get_search_query_path()) if config.discover_urls else []
    logger.info(
        "Initialized: %d URL(s) queued, %d discovery quer%s available",
        len(fetching_service.url_queue), len(discovery_queries),
        "y" if len(discovery_queries) == 1 else "ies",
    )
    # Finish work left over from an earlier run before fetching anything new,
    # so an interruption never leaves a permanently growing tail of
    # fetched-but-unprocessed pages.
    resume_pending()

def remember_frontier(config=None):
    """
    Save the queue, if this run is keeping it.

    Called after every round, so an interrupt costs at most one round's
    accumulated judgement about what to look at next.
    """
    config = config or config_service.get_config()
    if not getattr(config, "persist_frontier", False):
        return
    data_service.save_frontier(fetching_service.snapshot_frontier())


def recall_frontier(config=None):
    """
    Queue the frontier the last run left behind, if this run is keeping it.

    A frontier is worth keeping when a run was interrupted mid-stride. It is
    worth throwing away when the run had strayed - one 20-hour run ended with
    78,000 queued URLs, almost all of them human-health pages reached from
    misfiled advice pages, and resuming that queue would have resumed the
    drift. So a run that is not keeping the frontier also deletes the saved
    one rather than leaving it to ambush a later run.
    """
    config = config or config_service.get_config()
    if not getattr(config, "persist_frontier", False):
        data_service.clear_frontier()
        return
    fetching_service.restore_frontier(data_service.load_frontier())


def run_discovery():
    """
    Consume up to config.discovery_batch_size queries off the front of
    discovery_queries (generated by init()), run them against the
    configured search provider, and queue any newly discovered URLs for
    crawling. No-op if search-based discovery is disabled in the config, or
    if there are no queries left to consume.

    Queries are consumed (removed from discovery_queries) as they're used,
    so repeated calls work through the whole query list batch by batch
    instead of re-running the same queries - see run()'s docstring for why
    that matters.

    :return: number of URLs newly added to the fetch queue.
    """
    config = config_service.get_config()
    if not config.discover_urls or not discovery_queries:
        return 0
    batch = discovery_queries[:config.discovery_batch_size]
    del discovery_queries[:config.discovery_batch_size]
    discovered = discovery_service.discover_urls(
        config.get_search_provider(),
        batch,
        results_per_query=config.results_per_query,
        politeness=config.query_politeness,
    )
    added = discovery_service.queue_discovered_urls(discovered)
    monitor_service.discovery(
        queries_used=len(batch),
        discovered_unique=len(discovered),
        newly_queued=added,
        queries_remaining=len(discovery_queries),
    )
    logger.info("Discovery batch: %d new URL(s) queued (%d queries remaining)", added, len(discovery_queries))
    return added

def run():
    """
    Run the full crawl workflow end-to-end.

    init() seeds the fetch queue from starting_urls/prior crawls and
    generates (but does not yet run) the search-discovery queries. The
    fetch queue is then drained via process_batch() - which keeps it
    growing on its own as extraction discovers linked pages - and only once
    it runs completely dry does the workflow reach for search-engine
    discovery, via run_discovery(). That deliberately holds discovery back
    until crawling from the known/linked URLs has nothing left to do,
    rather than queuing every discovered URL upfront: it keeps discovery
    query usage proportional to how much the "cheap" crawl sources actually
    ran out, instead of firing every query in one burst regardless of need.

    Once run_discovery() has run, the loop goes back to draining the queue;
    if a discovery batch turned up nothing new, the next batch is tried
    (subject to the stopping conditions below) until either the queue has
    work again or there are no queries left.

    Stopping conditions (checked after every batch or discovery call, first
    one to trigger wins):
      - the fetch queue is empty AND there are no discovery queries left to try
      - config.max_discovery_batches discovery batches have been run (0 = no limit)
      - config.max_rounds fetch/process batches have been processed (0 = no limit)
      - config.max_runtime_seconds have elapsed since the run started (0 = no limit)
    """
    config = config_service.get_config()
    logger.info("Starting crawl run")
    monitor_service.start_session()
    init()

    queue_known_record_urls()

    start_time = time.monotonic()
    rounds = 0
    pipeline = _Pipeline(config) if getattr(config, "prefetch_next_batch", False) else None
    discovery_batches_used = 0
    stop_reason = "queue and discovery queries exhausted"

    def _time_or_round_limit_reached():
        nonlocal stop_reason
        if config.max_rounds and rounds >= config.max_rounds:
            stop_reason = f"reached max_rounds ({config.max_rounds})"
            return True
        if config.max_runtime_seconds and (time.monotonic() - start_time) >= config.max_runtime_seconds:
            stop_reason = f"reached max_runtime_seconds ({config.max_runtime_seconds})"
            return True
        return False

    def _frontier_is_unproductive():
        return frontier_is_unproductive(
            config, pipeline.pending_urls() if pipeline is not None else (),
            recent_yield)

    while True:
        if _frontier_is_unproductive():
            discovery_budget_left = not config.max_discovery_batches or discovery_batches_used < config.max_discovery_batches
            if not discovery_queries or not discovery_budget_left:
                if discovery_queries and not discovery_budget_left:
                    stop_reason = f"reached max_discovery_batches ({config.max_discovery_batches})"
                if fetching_service.url_queue:
                    # No discovery left, but there is still (low-value) work.
                    (pipeline.round if pipeline else process_batch)()
                    rounds += 1
                    if _time_or_round_limit_reached():
                        break
                    continue
                break  # nothing left to crawl, and no (more) discovery queries allowed
            run_discovery()
            discovery_batches_used += 1
            if _time_or_round_limit_reached():
                break
            continue  # queue may still be empty - loop back and try the next discovery batch

        (pipeline.round if pipeline else process_batch)()
        rounds += 1
        _log_frontier(rounds)
        remember_frontier(config)
        if _time_or_round_limit_reached():
            break

    if pipeline:
        pipeline.close()
    remember_frontier(config)

    elapsed = time.monotonic() - start_time
    logger.info(
        "Crawl run finished: %d batch(es), %d discovery batch(es), %.1fs elapsed (%s)",
        rounds, discovery_batches_used, elapsed, stop_reason,
    )
    monitor_service.session_end(rounds, discovery_batches_used, elapsed, stop_reason)

def process_batch(urls:list[str]|None=None):
    """
    Run one fetch-categorize-extract pass: fetch every URL currently queued
    (plus any given explicitly), categorize each successfully fetched page,
    extract structured data per its category, save everything to the
    database, and queue any linked pages extraction found for a future batch.

    Brackets the pass with monitor_service.round_start()/round_end() - see
    model.tools.monitor_service and experiments/analyze_session.py for how
    those timestamps are later used to bin this round's crawls (fetched/
    failed/categorized counts, all already in the database) out of the
    crawls table. Also times each page's categorize_website()/
    extract_information() calls individually and logs them via
    monitor_service.page() - unlike the round-level counts, this timing data
    only exists in the monitoring log, since the database doesn't record it.

    :param urls: extra URLs to queue before this batch runs, in addition to
                  whatever is already in fetching_service.url_queue.
    """

    ### Fetching
    if urls is not None:
        for url in urls:
            fetching_service.queue_url(url)

    config = config_service.get_config()
    batch, remainder = _take_batch(config)
    fetched = _fetch_and_record(batch)
    _analyse(fetched)
    _return_remainder(remainder)
    monitor_service.round_end()


def frontier_is_unproductive(config, pending_urls=(), recent_yield=()):
    """
    True when nothing worth crawling is left, so discovery should fire.

    Discovery used to fire only on a literally empty queue. Once link-following
    reaches the open web the queue never empties, so discovery never ran again
    and the crawl churned low-value pages indefinitely. Exhaustion has to mean
    "no promising work left", which is what discovery_when_below says.

    :param pending_urls: URLs already claimed for prefetching. They are out of
                          the queue but are still work in hand, so they count
                          here. Treating a claimed batch as a reason not to
                          judge the frontier at all was worse than either
                          alternative: with prefetching on there is nearly
                          always a batch in flight, and discovery never fired
                          once in five rounds of a live crawl whose best queued
                          score had fallen to -1.
    :param recent_yield: (pages worth extracting, pages fetched) for the last
                          rounds. Scores are a promise; this is what the pages
                          turned out to be. A run once spent twenty hours on
                          human-health sites with its best queued score never
                          below 3.0, because the weight feeding that score came
                          from a category the classifier was filling wrongly -
                          a mistake no amount of score-reading can catch.
    """
    if _yield_has_collapsed(config, recent_yield):
        return True
    queued = list(fetching_service.url_queue) + list(pending_urls)
    if not queued:
        return True
    threshold = config.discovery_when_below
    if not isinstance(threshold, (int, float)):
        return False
    best = max((fetching_service.url_priorities.get(url, 0.0) for url in queued),
               default=0.0)
    return best < threshold


def _yield_has_collapsed(config, recent_yield):
    """True when the last rounds fetched plenty and found almost nothing."""
    floor = getattr(config, "discovery_when_yield_below", 0.0)
    window = getattr(config, "yield_window_rounds", 0)
    if not isinstance(floor, (int, float)) or not isinstance(window, int):
        return False  # not configured, or a stand-in for one in a test
    if not floor or not window or len(recent_yield) < window:
        return False
    rounds = list(recent_yield)[-window:]
    fetched = sum(total for _, total in rounds)
    if not fetched:
        return False
    found = sum(worth for worth, _ in rounds)
    if found / fetched >= floor:
        return False
    logger.info("Frontier has strayed: %d of %d pages worth extracting over %d round(s)",
                found, fetched, window)
    return True


class _Pipeline:
    """
    Run one round's fetching while the previous round is analysed.

    A round fetched its pages and then analysed them with the network idle;
    fetching and its politeness delays were about a third of a measured run's
    wall-clock time. Here the next batch is claimed and handed to a worker
    thread as soon as this batch's pages are in hand, so the browser works
    while the GPU does.

    The cost is a less informed frontier: the next batch is chosen before this
    one's links are known, so a page linked from this round waits a round
    longer than it otherwise would. Only fetching runs in the worker - the
    database and the frontier stay with the caller.
    """

    def __init__(self, config):
        self._config = config
        self._pool = ThreadPoolExecutor(max_workers=1, thread_name_prefix="prefetch")
        self._pending = None  # (batch, future)

    def round(self):
        if self._pending is None:
            batch, remainder = _take_batch(self._config)
            _return_remainder(remainder)
            self._pending = (batch, self._pool.submit(fetch_batch, batch))
        batch, future = self._pending
        try:
            future.result()
        except Exception as e:
            logger.warning("Prefetching a batch failed (%s) - fetching it here instead", e)
            fetch_batch(batch)
        # Claim and start the next batch before analysing this one: that is
        # the whole point of the pipeline.
        next_batch, remainder = _take_batch(self._config)
        self._pending = ((next_batch, self._pool.submit(fetch_batch, next_batch))
                         if next_batch else None)
        fetched = _fetch_and_record(batch, already_fetched=True)
        _analyse(fetched)
        _return_remainder(remainder)
        monitor_service.round_end()

    def has_pending(self):
        return self._pending is not None

    def pending_urls(self):
        """The URLs of a batch already claimed and being fetched."""
        return list(self._pending[0]) if self._pending else []

    def close(self):
        self._pool.shutdown(wait=True)


def _log_frontier(round_number):
    """
    Report what the frontier looks like after a round.

    The best score says how far the crawl has strayed from anything worth
    extracting - the number discovery_when_below is compared against - so it
    belongs in the log beside the round it describes.
    """
    queue = fetching_service.url_queue
    if not queue:
        logger.info("Frontier after round %d: empty", round_number)
        return
    scores = sorted((fetching_service.url_priorities.get(u, 0.0) for u in queue), reverse=True)
    middle = scores[len(scores) // 2]
    logger.info("Frontier after round %d: %d URL(s), best %.2f, median %.2f",
                round_number, len(scores), scores[0], middle)


def _take_batch(config):
    """
    Claim this round's URLs from the frontier, best-first.

    Fetching is far cheaper than analysis, so an unbounded round fetches
    thousands of pages and then processes them one slow page at a time. They
    are durable either way, but the useful output (entries) lags far behind
    the crawling, and stopping mid-round leaves most of the work unfinished.
    Capping the round keeps fetching and processing in step.

    :return: (batch, remainder) - the remainder is put back after the round.
    """
    fetching_service.url_queue.sort(
        key=lambda u: fetching_service.url_priorities.get(u, 0.0), reverse=True)
    remainder = []
    if config.max_batch_size and len(fetching_service.url_queue) > config.max_batch_size:
        remainder = fetching_service.url_queue[config.max_batch_size:]
        fetching_service.url_queue = fetching_service.url_queue[:config.max_batch_size]
    batch = list(fetching_service.url_queue)
    fetching_service.url_queue = []
    return batch, remainder


def _return_remainder(remainder):
    """Put URLs held back from a round behind the links it discovered."""
    for url in remainder:
        if url not in fetching_service.url_queue:
            fetching_service.url_queue.append(url)


def fetch_batch(batch):
    """Fetch one claimed batch. Safe to run while another batch is analysed:
    it touches neither the frontier nor the database."""
    if batch:
        logger.info("Fetching %d URL(s)", len(batch))
        started = time.monotonic()
        asyncio.run(fetching_service.parse_queue(urls=batch))
        logger.info("Fetched %d URL(s) in %.0fs", len(batch), time.monotonic() - started)
    return batch


def _fetch_and_record(batch, already_fetched=False):
    """Fetch (unless already done) and write each page's crawl row.

    :return: [(crawl_id, Website)] for the pages that came back.
    """
    round_number = monitor_service.round_start(len(batch))
    logger.info("Processing batch of %d URL(s) (round %d)", len(batch), round_number)
    if not already_fetched:
        fetch_batch(batch)
    fetched = []
    for url in batch:
        html = asyncio.run(fetching_service.get_content(url))
        crawl_time = fetching_service.get_crawl_time(url)
        fetch_success = bool(html)
        # Persist the body *before* recording the crawl, so a row never points
        # at content that isn't on disk. The row's state stays non-terminal
        # until the page is actually processed, so an interruption here leaves
        # resumable work rather than a page marked done that never was.
        # Already persisted at fetch time (fetching_service.get_content); reuse
        # that path rather than storing the same bytes twice.
        digest, content_path = fetching_service.fetched_content.get(url, (None, None))
        if fetch_success and content_path is None:
            digest, content_path = page_store.store(html)
        crawl_id = data_service.save_crawl_instance(
            url, crawl_time, fetch_success,
            content_path=content_path, content_sha256=digest,
            site=url_service.registrable_domain(url),
            last_error=None if fetch_success else fetching_service.fetch_errors.get(url),
        )
        if fetch_success:
            fetched.append((crawl_id, Website(url=url, crawl_time=crawl_time, html=html)))
    if batch:
        logger.info("Fetched %d/%d URL(s) successfully", len(fetched), len(batch))
    return fetched


def _analyse(fetched):
    """Categorize and extract each fetched page, one at a time."""
    for crawl_id, website in fetched:
        process_page_safely(crawl_id, website.url, website.html)
    _record_round_yield(fetched)


def _record_round_yield(fetched):
    """Note how much of this round was worth extracting, for the drift alarm."""
    global _round_tally
    if not fetched and not _round_tally[1]:
        return
    recent_yield.append(tuple(_round_tally))
    del recent_yield[:-YIELD_HISTORY]
    _round_tally = [0, 0]


def process_page_safely(crawl_id:int, url:str, html:str, category=None):
    """
    process_page, but a failure on one page cannot end the run.

    Individual stages already handle the failures they expect. This catches
    the ones nobody expected: a single malformed link (urllib's "Invalid IPv6
    URL") once stopped an overnight crawl. The page is recorded as failed with
    the reason, so it is visible and not retried forever.
    """
    try:
        process_page(crawl_id, url, html, category)
    except Exception as e:
        logger.exception("Processing %s failed - marking it failed and continuing", url)
        data_service.set_crawl_state(crawl_id, data_service.STATE_FAILED,
                                     last_error=f"processing failed: {type(e).__name__}: {e}")


def process_page(crawl_id:int, url:str, html:str, category=None):
    """
    Take one fetched page from its current state to EXTRACTED.

    Each stage commits before the next begins, so an interruption leaves the
    page recorded at exactly the point it reached and a later run continues
    from there rather than refetching or reprocessing it.

    :param category: an already-determined Category (when resuming a page that
                      was categorized but not extracted); None to categorize now.
    """
    categorize_seconds = 0.0
    cfg = config_service.get_config()
    if category is None and getattr(cfg, "skip_identical_content", False):
        twin = data_service.find_analysed_twin(crawl_id)
        if twin is not None:
            twin_id, twin_category = twin
            # The same bytes cannot classify differently, and extracting them
            # again would only produce records the twin already carries - which
            # entity resolution would then have to merge back together.
            logger.info("Reusing the analysis of crawl %d for %s (identical content)", twin_id, url)
            data_service.save_site_category(crawl_id, twin_category)
            data_service.delete_entries_for_crawl(crawl_id)
            links = cleaning_service.extract_links_with_text(html, url)
            _queue_links(links, _category_named(cfg, twin_category, None), cfg, url)
            monitor_service.page(url, twin_category, 0.0, 0.0)
            data_service.set_crawl_state(crawl_id, data_service.STATE_EXTRACTED)
            return
    if category is None:
        categorize_start = time.monotonic()
        category = category_service.categorize_website(html, url)
        categorize_seconds = time.monotonic() - categorize_start
        if category is None:
            # category_service already logged why - one bad page (e.g. too
            # long for the model's context window) must not crash the run
            logger.warning("Skipping %s - categorization failed", url)
            monitor_service.page(url, None, categorize_seconds, 0.0)
            data_service.set_crawl_state(crawl_id, data_service.STATE_FAILED,
                                         last_error="categorization failed")
            return
        data_service.save_site_category(crawl_id, category.name)
        data_service.set_crawl_state(crawl_id, data_service.STATE_CATEGORIZED)
        logger.info("Categorized %s as %s", url, category.name)
        _round_tally[1] += 1
        _round_tally[0] += 1 if category.is_relevant else 0

    fetching_service.record_page_value(url, category)

    # A site that has already given up its details a few times has nothing
    # left to give. The classifier cannot be relied on to notice this: it is
    # inconsistent about which subpages introduce an organisation (observed on
    # one site, /geldspenden came back STATION while /sachspenden came back
    # HUB), and sites were producing twenty records that resolved to one
    # entity. Listing pages are exempt - each yields *different* entities, so
    # capping them would discard real data rather than redundancy.
    # Clear anything a previous attempt at this page wrote before deciding
    # anything else, so reprocessing (after a crash, or under a changed
    # taxonomy) can neither double-insert nor leave a page's old records behind
    # when it now yields none - and old records cannot count against the cap.
    data_service.delete_entries_for_crawl(crawl_id)

    cfg = config_service.get_config()
    if (cfg.max_extractions_per_site and category.is_relevant
            and not category.is_list_category):
        site = url_service.registrable_domain(url)
        already = data_service.count_extracted_pages_for_site(site)
        if already >= cfg.max_extractions_per_site:
            # The page's own links are still followed - a shelter's subpages
            # routinely link to other shelters, and parsing them costs an
            # HTML parse rather than an LLM call.
            links = cleaning_service.extract_links_with_text(html, url) if category.process_links else []
            logger.debug("Not extracting from %s - %s already yielded %d page(s) "
                         "of records; following %d link(s)",
                         url, site, already, len(links))
            _queue_links(links, category, cfg, url)
            monitor_service.page(url, category.name, categorize_seconds, 0.0)
            data_service.set_crawl_state(crawl_id, data_service.STATE_EXTRACTED)
            return

    extract_start = time.monotonic()
    extracted = extraction_service.extract_information(html, category, url)
    monitor_service.page(url, category.name, categorize_seconds, time.monotonic() - extract_start)

    if extracted:
        extracted_data, links = extracted
        if extracted_data is extraction_service.MISLABELED:
            # The extractor, which sees the whole page under instructions
            # describing exactly what this category is, judged it not to be
            # one. Store nothing, re-file the page, and remember what it was
            # first classified as: that is the evidence of where the
            # classifier goes wrong.
            cfg = config_service.get_config()
            target = cfg.mislabeled_category or cfg.url_prior_category or category.name
            data_service.reclassify_page(crawl_id, target, from_category=category.name)
            logger.info("Re-filed %s from %s to %s (judged mislabeled at extraction)",
                        url, category.name, target)
            # Links inherit the weight of what the page actually is, not of
            # the category it was wrongly given.
            _queue_links(links, _category_named(cfg, target, category), cfg, url)
            data_service.set_crawl_state(crawl_id, data_service.STATE_EXTRACTED)
            return
        if extracted_data is None:
            # Either a LINKS category (nothing on the page itself is worth
            # extracting) or a CONTENT category whose record failed the
            # admissibility gate. Both keep the page's outbound links.
            logger.debug("No content to extract from %s (category=%s), following %d link(s)", url, category.name, len(links))
        elif category.is_list_category:
            for entry in extracted_data:
                data_service.save_extraction(crawl_id, entry)
            logger.info("Extracted %d entries from %s", len(extracted_data), url)
            _queue_record_urls(extracted_data, category, config_service.get_config(), url)
        else:
            data_service.save_extraction(crawl_id, extracted_data)
            logger.info("Extracted %d field(s) from %s", len(extracted_data), url)
            _queue_record_urls([extracted_data], category, config_service.get_config(), url)
        _queue_links(links, category, config_service.get_config(), url)
    else:
        logger.debug("No data extracted from %s (category=%s)", url, category.name)

    data_service.set_crawl_state(crawl_id, data_service.STATE_EXTRACTED)


def _category_named(cfg, name, fallback):
    """The configured category called name, or fallback if there is none."""
    try:
        return cfg.get_category(name)
    except Exception:
        return fallback


def _queue_links(links, category, cfg, page_url=None):
    """
    Queue a page's outbound links, scored by the page that offered them.

    Links inherit a score from their referrer: pages found via a productive
    page are likelier to be productive themselves. They also inherit a
    *closeness* - the weight of the last interesting page on the way here,
    decayed once per hop. A crawl that follows links indiscriminately drifts:
    one run spent its night on Slovak charity sites and university
    departments, each page plausible on its own and none of them near a
    station. Decay makes distance cost something, and leaves the frontier's
    best score as a signal of how far the crawl has strayed - which is what
    tells discovery to fire.

    A link may arrive as a bare URL or as an (url, text) pair. The text is the
    words a reader would have clicked, which say more about what is at the
    other end than the URL does - see url_service.score_url.
    """
    weight = cfg.referrer_weights.get(category.name, 0.0)
    decay = getattr(cfg, "link_closeness_decay", 0.0) or 0.0
    source = weight if weight >= getattr(cfg, "closeness_source_min", 0.0) else         fetching_service.closeness_of(page_url)
    closeness = source * decay
    penalty = getattr(cfg, "leaving_site_penalty", 0.0) or 0.0
    exempt = weight >= getattr(cfg, "leaving_site_exempt_min_weight", 0.0)
    site = url_service.registrable_domain(page_url) if penalty and not exempt else None
    for link in links:
        link, text = link if isinstance(link, (tuple, list)) else (link, "")
        leaving = site is not None and url_service.registrable_domain(link) != site
        fetching_service.queue_url(
            link,
            priority=url_service.score_url(
                link, referrer_category_weight=weight,
                identity_tokens=cfg.url_tokens_identity,
                exclude_tokens=cfg.url_tokens_exclude,
                link_text=text,
                anchor_identity_tokens=getattr(cfg, "anchor_tokens_identity", ()),
                anchor_exclude_tokens=getattr(cfg, "anchor_tokens_exclude", ()),
                anchor_identity_bonus=getattr(cfg, "anchor_identity_bonus", 2.0),
                anchor_exclude_penalty=getattr(cfg, "anchor_exclude_penalty", 1.5))
            + closeness - (penalty if leaving else 0.0),
            closeness=closeness)


def queue_known_record_urls():
    """
    Queue the websites named in records already in the database that no crawl
    has visited.

    Following a record's own website only helps pages read during this run;
    26% of the websites named in one database had never been fetched, and
    those are the records that hold a name and a town and nothing else. They
    are queued at the priority the listing category uses, ahead of ordinary
    links.
    """
    cfg = config_service.get_config()
    if not getattr(cfg, "queue_record_urls_at_start", False):
        return 0
    url_fields = [name for name, sem in (cfg.field_semantics or {}).items()
                  if sem.get("normalize") == "url"]
    if not url_fields:
        return 0
    priority = max((c.record_url_priority for c in cfg.categories
                    if c.follow_record_urls), default=0.0)
    crawled = data_service.get_crawled_sites()
    queued = 0
    for field in url_fields:
        for value in data_service.get_record_urls(field):
            link = url_service.as_url(value)
            if not link or url_service.registrable_domain(link) in crawled:
                continue
            before = len(fetching_service.url_queue)
            fetching_service.queue_url(link, priority=priority)
            queued += len(fetching_service.url_queue) > before
    if queued:
        logger.info("Queued %d website(s) named in earlier records but never visited", queued)
    return queued


def _queue_record_urls(records, category, cfg, page_url):
    """
    Queue the websites named in extracted records, ahead of ordinary links.

    An organisation's own site is the best source for its details: a listing
    carries a name and a town, often nothing else, while the organisation's
    contact page has the address, phone and e-mail. Which fields hold such an
    address is read from the schema (normalize "url"), and links back into the
    listing's own site are left at their ordinary score - those are the
    directory's detail pages, not the organisation.
    """
    if not category.follow_record_urls:
        return
    url_fields = [name for name, sem in cfg.field_semantics.items() if sem.get("normalize") == "url"]
    page_site = url_service.registrable_domain(page_url)
    queued = 0
    for record in records:
        if not isinstance(record, dict):
            continue
        for field in url_fields:
            values = record.get(field)
            for value in values if isinstance(values, list) else [values]:
                link = url_service.as_url(value)
                if not link or url_service.registrable_domain(link) == page_site:
                    continue
                fetching_service.queue_url(link, priority=category.record_url_priority)
                queued += 1
    if queued:
        logger.info("Queued %d website(s) named in records from %s", queued, page_url)


def resume_pending(skip_over_budget=True):
    """
    Finish pages left unprocessed by an earlier run.

    Pages fetched but never categorized (or categorized but never extracted)
    are still in a non-terminal state, and their content is on disk, so they
    are resumed from exactly where they stopped - with no refetching. Content
    that has gone missing from the store is returned to the fetch queue rather
    than silently dropped.

    :param skip_over_budget: abandon pending pages from sites over the page
                              budget. Off for reprocessing, where every page
                              was already fetched and processed once: skipping
                              them then left their old records in the database
                              with no category (1,116 records in one reprocess).
    :return: number of pages processed.
    """
    # Sites that already blew through the page budget are not worth spending
    # further analysis on, whatever was fetched from them earlier.
    abandoned = 0
    if skip_over_budget:
        abandoned = data_service.skip_pending_over_budget(
            config_service.get_config().max_pages_per_site)
    if abandoned:
        logger.info("Abandoned %d unprocessed page(s) from sites over the page budget", abandoned)

    pending = data_service.get_pending_crawls()
    if not pending:
        return 0

    logger.info("Resuming %d unprocessed page(s) from a previous run", len(pending))
    processed = 0
    for row in pending:
        html = page_store.load(row["content_path"])
        if not html:
            logger.warning("Stored content missing for %s - requeueing", row["source_url"])
            data_service.set_crawl_state(row["crawl_id"], data_service.STATE_FETCH_FAILED,
                                         last_error="stored content missing")
            fetching_service.queue_url(row["source_url"])
            continue
        category = None
        if row["category"]:
            try:
                category = config_service.get_config().get_category(row["category"])
            except Exception:
                category = None  # category set no longer matches config - redo it
        # This page is being handled from the store; without claiming the URL
        # here, a link to it found later in the run would queue it for a fresh
        # fetch, producing a second crawl row and a duplicate set of records.
        fetching_service.mark_processed(row["source_url"])
        process_page_safely(row["crawl_id"], row["source_url"], html, category)
        processed += 1
    logger.info("Resumed %d page(s)", processed)
    return processed

def resolve_entities():
    """
    Deduplicate the observation records in `entries` into `entities`.

    Runs blocking -> scoring -> clustering -> fusion over everything extracted
    so far, using the field roles declared in the config, and replaces the
    entity layer with the result. `entries` itself is never modified, so this
    can be re-run after tuning weights without re-crawling.

    :return: (record_count, entity_count)
    """
    config = config_service.get_config()
    data_service.init_db()
    data_service.init_entity_tables()

    records = data_service.get_entries_with_source()
    if not records:
        logger.info("No extracted records to resolve")
        return 0, 0

    for record in records:
        # A record found on the entity's own site outranks one copied into a
        # third-party directory, which is often abbreviated or stale.
        own = url_service.registrable_domain(record.get("station_url") or "")
        source = url_service.registrable_domain(record.get("_source_url") or "")
        record["_trust"] = 1.0 if own and own == source else 0.5

    resolver = entity_service.Resolver(field_semantics=config.field_semantics)
    clusters = resolver.cluster(records)
    resolved = [(resolver.fuse(cluster), [r["entry_id"] for r in cluster])
                for cluster in clusters]
    data_service.replace_entities(resolved)

    logger.info("Resolved %d record(s) into %d entit%s (%.1f%% duplicates removed)",
                len(records), len(clusters), "y" if len(clusters) == 1 else "ies",
                100 * (1 - len(clusters) / len(records)))
    return len(records), len(clusters)


def reprocess(stage="extract", where_site=None, where_category=None):
    """
    Re-run analysis over already-stored pages, without any network traffic.

    Because every fetched body is kept in the page store, categorization and
    extraction can be redone after changing a prompt, a model, a token budget
    or the schema - on exactly the same corpus, which is what makes such
    comparisons controlled rather than confounded by a re-crawl.

    :param stage: "extract" re-runs extraction only (keeping categories);
                   "categorize" re-runs classification as well.
    :param where_site: limit to one registrable domain.
    :param where_category: limit to pages currently in this category - the
                            surgical form, for when a prompt change moves one
                            boundary and the rest of the corpus is still right.
    :return: number of pages queued for reprocessing.
    """
    data_service.init_db()
    page_store.configure(config_service.get_config().page_store_path)
    target = (data_service.STATE_CATEGORIZED if stage == "extract"
              else data_service.STATE_FETCHED)
    reset = data_service.reset_states_for_reprocess(
        target, site=where_site, category=where_category)
    logger.info("Reset %d page(s) to %s for reprocessing", reset, target)
    processed = resume_pending(skip_over_budget=False)
    logger.info("Reprocessed %d page(s) with no refetching", processed)
    return processed
